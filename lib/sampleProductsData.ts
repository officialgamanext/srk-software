// Helper to trigger browser download of the 100 Sample Products Excel File
export async function download100SampleProductsExcel() {
  const XLSX = await import("xlsx");
  const worksheet = XLSX.utils.json_to_sheet(SAMPLE_100_PRODUCTS);

  // Set column widths for beautiful Excel formatting
  worksheet["!cols"] = [
    { wch: 38 }, // Title
    { wch: 22 }, // Category
    { wch: 15 }, // SKU
    { wch: 14 }, // Barcode
    { wch: 15 }, // Shortcode
    { wch: 18 }, // MRP
    { wch: 14 }, // Sale Price
    { wch: 14 }, // GST %
    { wch: 12 }, // Tax Type
    { wch: 14 }, // Stock
    { wch: 10 }, // Status
    { wch: 45 }, // Description
  ];

  const workbook = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(workbook, worksheet, "100 Master Products");
  XLSX.writeFile(workbook, "sample_100_master_retail_products.xlsx");
}
